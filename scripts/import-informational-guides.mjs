import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const sourceRoot = join(root, "Guide Infor");
const contentRoot = join(root, "public", "content", "informational");
const registryFile = join(root, "data", "informational-guides.generated.ts");

function parseFrontmatter(source, filename) {
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/);
  if (!match) throw new Error(`Missing frontmatter: ${filename}`);

  const fields = {};
  for (const line of match[1].split(/\r?\n/)) {
    const separator = line.indexOf(":");
    if (separator < 0) continue;
    const key = line.slice(0, separator).trim();
    let value = line.slice(separator + 1).trim();
    if (value.startsWith('"') && value.endsWith('"')) value = value.slice(1, -1);
    fields[key] = value;
  }
  return { fields, markdown: match[2].trim() + "\n" };
}

function plainText(markdown) {
  return markdown
    .replace(/!\[[^\]]*\]\([^)]+\)/g, "")
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    .replace(/[*_`>#]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function firstParagraph(markdown) {
  const withoutTitle = markdown.replace(/^# .+\r?\n+/, "");
  const paragraph = withoutTitle.split(/\r?\n\s*\r?\n/).find((block) => !/^[-#|>]/.test(block.trim()));
  return plainText(paragraph ?? "");
}

const articleFiles = readdirSync(sourceRoot, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .flatMap((directory) =>
    readdirSync(join(sourceRoot, directory.name))
      .filter((filename) => /^\d{2,3}-.+\.md$/.test(filename))
      .map((filename) => join(sourceRoot, directory.name, filename))
  )
  .sort((a, b) => Number(basename(a).match(/^\d+/)?.[0]) - Number(basename(b).match(/^\d+/)?.[0]));

mkdirSync(contentRoot, { recursive: true });

const guides = articleFiles.map((file) => {
  const filename = basename(file);
  const number = Number(filename.match(/^\d+/)?.[0]);
  const { fields, markdown } = parseFrontmatter(readFileSync(file, "utf8"), filename);
  const slug = fields.slug.replace(/^\/+|\/+$/g, "");
  const contentFile = `${slug}.md`;
  const wordCount = plainText(markdown).split(/\s+/).filter(Boolean).length;

  writeFileSync(join(contentRoot, contentFile), markdown, "utf8");

  return {
    slug,
    silo: fields.silo || (number >= 21 ? "tents-shelter" : "campsite-gear"),
    title: fields.title,
    metaTitle: fields.title,
    description: fields.meta_description,
    dek: firstParagraph(markdown),
    directAnswer: firstParagraph(markdown),
    readTime: `${Math.max(1, Math.ceil(wordCount / 200))} min`,
    lastUpdated: "2026-10-06",
    keyTakeaways: [],
    sections: [],
    faq: [],
    sources: [],
    related: [],
    contentFile,
  };
});

const output = `// AUTO-GENERATED by scripts/import-informational-guides.mjs - do not hand-edit.\n` +
  `import type { InformationalGuide } from "@/data/informational-guides";\n\n` +
  `export const generatedInformationalGuides: InformationalGuide[] = ${JSON.stringify(guides, null, 2)};\n`;

writeFileSync(registryFile, output, "utf8");
console.log(`Imported ${guides.length} informational guides.`);
